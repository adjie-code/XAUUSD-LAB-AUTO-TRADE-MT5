#!/usr/bin/env python3
"""
Generator EA MQL5 dari hasil backtest Strategy Tester.

- Hanya mendukung strategi `ema_cross` (baseline) untuk versi pertama.
- Output ke `ea/generated/`, tidak pernah menimpa EA aktif.
- EA hasil generator:
  - DEMO only
  - magic sendiri
  - hanya mengelola posisinya sendiri
  - entry EMA cross + ATR SL/TP, satu posisi
- Tidak mengirim order dan tidak mengubah EA/PULLBACK yang sedang berjalan.
"""
from __future__ import annotations

import hashlib
import json
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "backtest" / "results"
EA_DIR = ROOT / "ea" / "generated"
INDEX = EA_DIR / "index.json"
RUN_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
NAME_RE = re.compile(r"[^A-Za-z0-9_-]+")
RESERVED_MAGICS = {20261111, 20261113, 20261114, 20261115, 20261116}


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def evaluate_summary(summary: dict) -> dict:
    gates = [
        ("Trades ≥ 100", summary.get("trades", 0), 100,
         (summary.get("trades") or 0) >= 100),
        ("Net PnL > 0", summary.get("net_pnl", 0), 0,
         (summary.get("net_pnl") or 0) > 0),
        ("Profit factor ≥ 1.2", summary.get("profit_factor"), 1.2,
         (summary.get("profit_factor") is not None and
          float(summary.get("profit_factor")) >= 1.2)),
        ("Max DD ≤ 20%", summary.get("max_drawdown_pct"), 20,
         (summary.get("max_drawdown_pct") is not None and
          float(summary.get("max_drawdown_pct")) <= 20)),
        ("Periode ≥ 5 tahun", summary.get("years"), 5,
         (summary.get("years") or 0) >= 5),
    ]
    passed = sum(1 for g in gates if g[3])
    net = summary.get("net_pnl") or 0
    trades = summary.get("trades") or 0
    dd = summary.get("max_drawdown_pct")
    if passed == len(gates):
        verdict = "Layak diuji"
    elif net > 0 and trades >= 30 and dd is not None and float(dd) <= 40:
        verdict = "Perlu revisi"
    else:
        verdict = "Tolak"
    return {
        "verdict": verdict,
        "score": f"{passed}/{len(gates)}",
        "gates": [
            {"label": g[0], "value": g[1], "threshold": g[2], "pass": g[3]}
            for g in gates
        ],
    }


def _load_job(job_id: str) -> tuple[dict | None, str]:
    if not RUN_ID_RE.match(job_id):
        return None, "id job tidak valid"
    summary_path = RESULTS / f"run_{job_id}" / "summary.json"
    if not summary_path.is_file():
        return None, "hasil backtest belum ada"
    try:
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None, "summary.json tidak valid"
    if summary.get("strategy") != "ema_cross":
        return None, "generator saat ini hanya mendukung ema_cross"
    return summary, ""


def _safe_name(name: str | None, job_id: str) -> str:
    base = (name or f"ema_cross_{job_id}").strip()
    base = NAME_RE.sub("_", base).strip("_")
    if not base:
        base = f"ema_cross_{job_id}"
    return base[:60]


def _used_magics() -> set[int]:
    used = set(RESERVED_MAGICS)
    for item in list_generated(200):
        try:
            used.add(int(item.get("magic")))
        except (TypeError, ValueError):
            continue
    return used


def _next_magic(job_id: str, requested: int | None) -> int:
    used = _used_magics()
    if requested is not None:
        magic = int(requested)
        if magic in used or magic <= 0:
            raise ValueError("magic sudah dipakai / bentrok dengan strategi aktif")
        return magic
    base = 20261115 + (int(hashlib.md5(job_id.encode()).hexdigest()[:4], 16) % 800)
    while base in used:
        base += 1
    return base


def _render(summary: dict, name: str, magic: int, job_id: str) -> str:
    p = summary.get("params") or {}
    data = summary.get("data") or {}
    verdict = evaluate_summary(summary)
    tpl = Template(r'''//+------------------------------------------------------------------+
//|  Generated by XAUUSD Strategy Lab — DEMO ONLY                    |
//|  File   : $FILE
//|  Job    : $JOB_ID
//|  Sumber : $SOURCE
//|  Aturan : EMA $FAST/$SLOW cross + ATR $ATR SL/TP
//|  Verdict: $VERDICT ($SCORE)
//|                                                                  |
//|  JANGAN pasang EA ini di chart yang sama dengan EA utama.         |
//|  EA ini hanya mengelola posisi dengan magic-nya sendiri.          |
//+------------------------------------------------------------------+
#property copyright "XAUUSD Pattern Lab"
#property version   "1.00"
#property description "Generated EA — DEMO only. Backtest Python, bukan jaminan live."

#include <Trade\Trade.mqh>

input string InpSymbol          = "$SYMBOL";       // symbol
input long   InpMagic           = $MAGIC;          // magic khusus EA generated
input double InpLot             = $LOT;            // lot tetap
input int    InpFastEMA         = $FAST;           // EMA cepat M5
input int    InpSlowEMA         = $SLOW;           // EMA lambat M5
input int    InpATRPeriod       = $ATR;            // ATR M5
input double InpSLATR           = $SL_ATR;         // SL x ATR
input double InpTPATR           = $TP_ATR;         // TP x ATR
input int    InpMaxSpreadPoints = $SPREAD;         // spread maksimal (poin)

CTrade trade;
int    hFast = INVALID_HANDLE;
int    hSlow = INVALID_HANDLE;
int    hATR  = INVALID_HANDLE;
datetime lastBar = 0;

bool IsNewBar()
{
   datetime t = iTime(InpSymbol, PERIOD_M5, 0);
   if(t == 0)
      return false;
   if(t == lastBar)
      return false;
   lastBar = t;
   return true;
}

int OwnPositions()
{
   int n = 0;
   for(int i = PositionsTotal() - 1; i >= 0; i--)
   {
      ulong ticket = PositionGetTicket(i);
      if(ticket == 0)
         continue;
      if(PositionGetString(POSITION_SYMBOL) != InpSymbol)
         continue;
      if((long)PositionGetInteger(POSITION_MAGIC) == InpMagic)
         n++;
   }
   return n;
}

bool StopsValid(bool isBuy, double bid, double ask, double sl, double tp)
{
   double point = SymbolInfoDouble(InpSymbol, SYMBOL_POINT);
   long stops = SymbolInfoInteger(InpSymbol, SYMBOL_TRADE_STOPS_LEVEL);
   double minDist = (double)stops * point;
   if(isBuy)
      return (sl < bid - minDist && tp > ask + minDist);
   return (sl > ask + minDist && tp < bid - minDist);
}

int OnInit()
{
   if(AccountInfoInteger(ACCOUNT_TRADE_MODE) != ACCOUNT_TRADE_MODE_DEMO)
   {
      Print("EA generated menolak akun non-DEMO.");
      return INIT_FAILED;
   }
   if(!SymbolSelect(InpSymbol, true))
   {
      Print("Symbol tidak tersedia: ", InpSymbol);
      return INIT_FAILED;
   }
   if(InpLot <= 0.0 || InpFastEMA < 2 || InpSlowEMA <= InpFastEMA ||
      InpATRPeriod < 2 || InpSLATR <= 0.0 || InpTPATR <= 0.0)
   {
      Print("Input tidak valid.");
      return INIT_FAILED;
   }

   hFast = iMA(InpSymbol, PERIOD_M5, InpFastEMA, 0, MODE_EMA, PRICE_CLOSE);
   hSlow = iMA(InpSymbol, PERIOD_M5, InpSlowEMA, 0, MODE_EMA, PRICE_CLOSE);
   hATR  = iATR(InpSymbol, PERIOD_M5, InpATRPeriod);
   if(hFast == INVALID_HANDLE || hSlow == INVALID_HANDLE || hATR == INVALID_HANDLE)
   {
      Print("Gagal membuat handle indikator.");
      return INIT_FAILED;
   }

   trade.SetExpertMagicNumber((ulong)InpMagic);
   trade.SetDeviationInPoints(30);
   trade.SetTypeFillingBySymbol(InpSymbol);

   lastBar = iTime(InpSymbol, PERIOD_M5, 0);
   Print("Generated EA aktif | magic=", InpMagic, " symbol=", InpSymbol);
   return INIT_SUCCEEDED;
}

void OnDeinit(const int reason)
{
   if(hFast != INVALID_HANDLE) IndicatorRelease(hFast);
   if(hSlow != INVALID_HANDLE) IndicatorRelease(hSlow);
   if(hATR  != INVALID_HANDLE) IndicatorRelease(hATR);
}

void OnTick()
{
   if(!IsNewBar())
      return;
   if(OwnPositions() > 0)
      return;

   MqlTick tick;
   if(!SymbolInfoTick(InpSymbol, tick))
      return;
   if(tick.bid <= 0.0 || tick.ask <= 0.0)
      return;

   double point = SymbolInfoDouble(InpSymbol, SYMBOL_POINT);
   if(point <= 0.0)
      return;
   if(InpMaxSpreadPoints > 0 &&
      (tick.ask - tick.bid) / point > (double)InpMaxSpreadPoints)
      return;

   double fast[2], slow[2], atr[1];
   if(CopyBuffer(hFast, 0, 1, 2, fast) != 2) return;
   if(CopyBuffer(hSlow, 0, 1, 2, slow) != 2) return;
   if(CopyBuffer(hATR,  0, 1, 1, atr)  != 1) return;
   if(atr[0] <= 0.0) return;

   bool up = (fast[0] > slow[0] && fast[1] <= slow[1]);
   bool dn = (fast[0] < slow[0] && fast[1] >= slow[1]);
   if(!up && !dn)
      return;

   int digits = (int)SymbolInfoInteger(InpSymbol, SYMBOL_DIGITS);
   double sl, tp;
   if(up)
   {
      sl = NormalizeDouble(tick.ask - atr[0] * InpSLATR, digits);
      tp = NormalizeDouble(tick.ask + atr[0] * InpTPATR, digits);
      if(!StopsValid(true, tick.bid, tick.ask, sl, tp))
         return;
      trade.Buy(InpLot, InpSymbol, 0.0, sl, tp, "GEN-EMA");
   }
   else
   {
      sl = NormalizeDouble(tick.bid + atr[0] * InpSLATR, digits);
      tp = NormalizeDouble(tick.bid - atr[0] * InpTPATR, digits);
      if(!StopsValid(false, tick.bid, tick.ask, sl, tp))
         return;
      trade.Sell(InpLot, InpSymbol, 0.0, sl, tp, "GEN-EMA");
   }
}
''')
    return tpl.safe_substitute(
        FILE=f"XAUUSD_{name}_{job_id}.mq5",
        JOB_ID=job_id,
        SOURCE=data.get("start", "?") + " → " + data.get("end", "?"),
        VERDICT=verdict["verdict"],
        SCORE=verdict["score"],
        SYMBOL="XAUUSD",
        MAGIC=str(magic),
        LOT=f"{float(p.get('lot', 0.01)):.2f}",
        FAST=str(int(p.get("fast", 20))),
        SLOW=str(int(p.get("slow", 50))),
        ATR=str(int(p.get("atr", 14))),
        SL_ATR=f"{float(p.get('sl_atr', 1.5)):.2f}",
        TP_ATR=f"{float(p.get('tp_atr', 2.5)):.2f}",
        SPREAD=str(max(0, int(round(float(p.get("spread_points", 30)))))),
    )


def generate_from_job(job_id: str, name: str | None = None,
                      magic: int | None = None) -> tuple[dict | None, str]:
    summary, err = _load_job(job_id)
    if err:
        return None, err
    try:
        magic_val = _next_magic(job_id, magic)
    except (TypeError, ValueError) as exc:
        return None, str(exc)
    safe = _safe_name(name, job_id)
    EA_DIR.mkdir(parents=True, exist_ok=True)
    path = EA_DIR / f"XAUUSD_{safe}_{job_id}.mq5"
    if path.exists():
        return None, f"file sudah ada: {path.name}"
    source = _render(summary, safe, magic_val, job_id)
    path.write_text(source, encoding="utf-8")
    verdict = evaluate_summary(summary)
    meta = {
        "file": path.name,
        "path": str(path),
        "job_id": job_id,
        "name": safe,
        "magic": magic_val,
        "strategy": summary.get("strategy"),
        "params": summary.get("params"),
        "verdict": verdict["verdict"],
        "score": verdict["score"],
        "created_at": utc_now(),
        "demo_only": True,
        "note": "Generated dari backtest Python; validasi ulang di MT5.",
    }
    (RESULTS / f"run_{job_id}" / "ea_meta.json").write_text(
        json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    _append_index(meta)
    return meta, ""


def _append_index(meta: dict) -> None:
    items = []
    if INDEX.is_file():
        try:
            items = json.loads(INDEX.read_text(encoding="utf-8"))
            if not isinstance(items, list):
                items = []
        except (OSError, ValueError):
            items = []
    items = [x for x in items if isinstance(x, dict) and x.get("file") != meta["file"]]
    items.append(meta)
    INDEX.write_text(json.dumps(items[-200:], indent=2, ensure_ascii=False) + "\n",
                     encoding="utf-8")


def list_generated(limit: int = 50) -> list[dict]:
    if not INDEX.is_file():
        return []
    try:
        items = json.loads(INDEX.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    if not isinstance(items, list):
        return []
    return [x for x in items if isinstance(x, dict) and (EA_DIR / x.get("file", "")).is_file()][-limit:][::-1]


def read_ea(filename: str) -> tuple[bytes | None, str]:
    if not re.fullmatch(r"[A-Za-z0-9_.-]+\.mq5", filename or ""):
        return None, "nama file tidak valid"
    path = (EA_DIR / filename).resolve()
    try:
        path.relative_to(EA_DIR.resolve())
    except ValueError:
        return None, "path tidak valid"
    if not path.is_file():
        return None, "file tidak ada"
    return path.read_bytes(), "text/plain; charset=utf-8"
